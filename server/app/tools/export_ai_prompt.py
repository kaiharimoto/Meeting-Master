"""Write the external-AI prompt into the laptop app, so Copy/Save AI prompt
works with no home server (a transcript loaded from a file while away).

summarize.external_prompt() stays the single source of truth: this renders it
with placeholder tokens and writes the result to
app/src/renderer/js/aiPromptText.js. tests/test_prompt_parity.py fails when
that file is stale — run this after changing any prompt text:

    cd server && python -m app.tools.export_ai_prompt
"""

import json
from pathlib import Path

from ..models import MeetingMeta
from ..pipeline import _ollama
from ..pipeline.summarize import external_prompt

CONTEXT_TOKEN = "{{MM_MEETING_CONTEXT}}"
TRANSCRIPT_TOKEN = "{{MM_TRANSCRIPT}}"

TARGET = (
    Path(__file__).resolve().parents[3] / "app" / "src" / "renderer" / "js" / "aiPromptText.js"
)


def template() -> str:
    """external_prompt() with the meeting context and transcript as tokens."""
    meeting = MeetingMeta.model_validate(
        {"schemaVersion": 1, "details": {"title": "\x01", "date": "\x02", "time": "\x03",
                                         "attendees": ["\x04"]}, "cards": []}
    )
    context = _ollama.meeting_context(meeting)
    text = external_prompt(TRANSCRIPT_TOKEN, meeting)
    if text.count(context) != 1:
        raise RuntimeError("meeting context must appear exactly once in external_prompt()")
    return text.replace(context, CONTEXT_TOKEN)


def render_js() -> str:
    return (
        "// GENERATED by `cd server && python -m app.tools.export_ai_prompt` from\n"
        "// summarize.external_prompt() — do not edit by hand; edit the Python and\n"
        "// re-run. tests/test_prompt_parity.py fails when this file is stale.\n\n"
        f"export const CONTEXT_TOKEN = {json.dumps(CONTEXT_TOKEN)};\n"
        f"export const TRANSCRIPT_TOKEN = {json.dumps(TRANSCRIPT_TOKEN)};\n"
        f"export const PROMPT_TEMPLATE = {json.dumps(template(), ensure_ascii=False)};\n"
    )


if __name__ == "__main__":
    TARGET.write_text(render_js(), encoding="utf-8")
    print(f"wrote {TARGET}")
